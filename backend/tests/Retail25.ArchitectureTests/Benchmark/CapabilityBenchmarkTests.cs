using System.Globalization;
using System.Reflection;
using System.Text;
using FluentAssertions;
using Xunit;
using Xunit.Abstractions;

namespace Retail25.ArchitectureTests.Benchmark;

/// <summary>
/// Runs the functional-parity benchmark and writes <c>docs/BENCHMARK.md</c>.
/// <para>
/// This is the project's honesty mechanism. Every legacy behaviour names the code that must exist
/// for it to count as delivered, and the check is reflection over the compiled assemblies. Nobody
/// can raise the score by editing a document — only by writing the code.
/// </para>
/// </summary>
public class CapabilityBenchmarkTests
{
    /// <summary>
    /// Coverage floor. Raise it as capabilities land; the assertion then stops a regression from
    /// quietly removing working behaviour.
    /// </summary>
    private const decimal MinimumImplementedPercent = 45m;

    private readonly ITestOutputHelper _output;

    public CapabilityBenchmarkTests(ITestOutputHelper output) => _output = output;

    [Fact]
    public void Every_capability_claim_resolves_to_real_code()
    {
        var results = Evaluate();

        // A claim that names a type which does not exist is not a failure — it is the registry
        // recording work that is still to do. What must never happen is a claim that is partly
        // resolvable being read as complete, which the state machine already prevents.
        var partial = results.Where(r => r.State == CapabilityState.Partial).ToList();

        foreach (var result in partial)
        {
            _output.WriteLine(
                $"PARTIAL {result.Capability.Id}: {result.Capability.Feature} — missing {string.Join(", ", result.Unresolved)}");
        }

        results.Should().NotBeEmpty("the capability registry must describe the legacy system");
    }

    [Fact]
    public void Delivered_coverage_has_not_regressed()
    {
        var results = Evaluate();
        var implemented = results.Count(r => r.State == CapabilityState.Implemented);
        var percent = decimal.Round(implemented * 100m / results.Count, 1);

        _output.WriteLine($"Implemented {implemented}/{results.Count} ({percent}%)");

        percent.Should().BeGreaterThanOrEqualTo(
            MinimumImplementedPercent,
            "capabilities that were working must not silently stop working");
    }

    [Fact]
    public void Writes_the_benchmark_report()
    {
        var results = Evaluate();
        var markdown = BuildReport(results);

        var path = Path.Combine(RepositoryRoot(), "docs", "BENCHMARK.md");
        Directory.CreateDirectory(Path.GetDirectoryName(path)!);
        File.WriteAllText(path, markdown, Encoding.UTF8);

        _output.WriteLine($"Wrote {path}");
        File.Exists(path).Should().BeTrue();
    }

    private static IReadOnlyList<CapabilityResult> Evaluate()
    {
        var registryPath = Path.Combine(AppContext.BaseDirectory, "Benchmark", "capabilities.json");
        var capabilities = CapabilityRegistry.Load(registryPath);

        return CapabilityRegistry.Evaluate(capabilities, LoadAssemblies());
    }

    /// <summary>
    /// Loads every Retail25 assembly next to the test binaries. Test assemblies are included so a
    /// capability can cite the test that proves it, not merely the class that implements it.
    /// </summary>
    private static IReadOnlyList<Assembly> LoadAssemblies()
    {
        var loaded = new List<Assembly>();

        foreach (var file in Directory.GetFiles(AppContext.BaseDirectory, "Retail25*.dll"))
        {
            try
            {
                loaded.Add(Assembly.LoadFrom(file));
            }
            catch (BadImageFormatException)
            {
                // Native or mixed-mode file that happens to match the pattern.
            }
            catch (FileLoadException)
            {
                // Already loaded under a different context.
            }
        }

        return loaded;
    }

    private static string BuildReport(IReadOnlyList<CapabilityResult> results)
    {
        var culture = CultureInfo.InvariantCulture;
        var builder = new StringBuilder();

        var implemented = results.Count(r => r.State == CapabilityState.Implemented);
        var partial = results.Count(r => r.State == CapabilityState.Partial);
        var missing = results.Count(r => r.State == CapabilityState.Missing);

        builder.AppendLine("# Retail25 — Functional Parity Benchmark");
        builder.AppendLine();
        builder.AppendLine("> Generated by `Retail25.ArchitectureTests.Benchmark.CapabilityBenchmarkTests`.");
        builder.AppendLine("> Do not edit by hand — every row is verified by reflection against the compiled");
        builder.AppendLine("> assemblies. A feature counts as delivered only when the code it names exists.");
        builder.AppendLine();
        builder.AppendLine(culture, $"Generated {DateTimeOffset.UtcNow:yyyy-MM-dd HH:mm} UTC");
        builder.AppendLine();

        builder.AppendLine("## Summary");
        builder.AppendLine();
        builder.AppendLine("| State | Count | Share |");
        builder.AppendLine("|---|---:|---:|");
        AppendSummaryRow(builder, culture, "✅ Implemented", implemented, results.Count);
        AppendSummaryRow(builder, culture, "🟡 Partial", partial, results.Count);
        AppendSummaryRow(builder, culture, "⬜ Not started", missing, results.Count);
        builder.AppendLine(culture, $"| **Total** | **{results.Count}** | |");
        builder.AppendLine();

        builder.AppendLine("## By area");
        builder.AppendLine();
        builder.AppendLine("| Area | Implemented | Partial | Not started |");
        builder.AppendLine("|---|---:|---:|---:|");

        foreach (var area in results.GroupBy(r => r.Capability.Area).OrderBy(g => g.Key, StringComparer.Ordinal))
        {
            builder.AppendLine(culture,
                $"| {area.Key} | {area.Count(r => r.State == CapabilityState.Implemented)} " +
                $"| {area.Count(r => r.State == CapabilityState.Partial)} " +
                $"| {area.Count(r => r.State == CapabilityState.Missing)} |");
        }

        builder.AppendLine();
        builder.AppendLine("## By delivery phase");
        builder.AppendLine();
        builder.AppendLine("| Phase | Implemented | Partial | Not started |");
        builder.AppendLine("|---:|---:|---:|---:|");

        foreach (var phase in results.GroupBy(r => r.Capability.Phase).OrderBy(g => g.Key))
        {
            builder.AppendLine(culture,
                $"| {phase.Key} | {phase.Count(r => r.State == CapabilityState.Implemented)} " +
                $"| {phase.Count(r => r.State == CapabilityState.Partial)} " +
                $"| {phase.Count(r => r.State == CapabilityState.Missing)} |");
        }

        builder.AppendLine();
        builder.AppendLine("## Detail");

        foreach (var area in results.GroupBy(r => r.Capability.Area).OrderBy(g => g.Key, StringComparer.Ordinal))
        {
            builder.AppendLine();
            builder.AppendLine(culture, $"### {area.Key}");
            builder.AppendLine();
            builder.AppendLine("| | ID | Feature | Guide | Phase | Missing evidence |");
            builder.AppendLine("|---|---|---|---|---:|---|");

            foreach (var result in area.OrderBy(r => r.Capability.Id, StringComparer.Ordinal))
            {
                var icon = result.State switch
                {
                    CapabilityState.Implemented => "✅",
                    CapabilityState.Partial => "🟡",
                    _ => "⬜",
                };

                var gaps = result.Unresolved.Count == 0
                    ? (result.Capability.Requires.Count == 0 ? "_nothing claimed_" : "—")
                    : string.Join("<br>", result.Unresolved.Select(u => $"`{Shorten(u)}`"));

                builder.AppendLine(culture,
                    $"| {icon} | {result.Capability.Id} | {result.Capability.Feature} " +
                    $"| {result.Capability.GuideRef} | {result.Capability.Phase} | {gaps} |");
            }
        }

        return builder.ToString();
    }

    private static void AppendSummaryRow(StringBuilder builder, CultureInfo culture, string label, int count, int total)
    {
        var share = total == 0 ? 0m : decimal.Round(count * 100m / total, 1);
        builder.AppendLine(culture, $"| {label} | {count} | {share}% |");
    }

    /// <summary>Trims a namespace down to the part a reader needs to recognise it.</summary>
    private static string Shorten(string reference)
    {
        var hash = reference.LastIndexOf('#');
        var typePart = hash > 0 ? reference[..hash] : reference;
        var memberPart = hash > 0 ? reference[hash..] : string.Empty;

        var lastDot = typePart.LastIndexOf('.');
        var shortType = lastDot > 0 ? typePart[(lastDot + 1)..] : typePart;

        return shortType + memberPart;
    }

    /// <summary>
    /// Walks up from the test binaries to the repository root. Anchored on the docs folder so it
    /// does not depend on how deep the build output happens to be.
    /// </summary>
    private static string RepositoryRoot()
    {
        var directory = new DirectoryInfo(AppContext.BaseDirectory);

        while (directory is not null)
        {
            if (Directory.Exists(Path.Combine(directory.FullName, "docs"))
                && Directory.Exists(Path.Combine(directory.FullName, "backend")))
            {
                return directory.FullName;
            }

            directory = directory.Parent;
        }

        throw new DirectoryNotFoundException("Could not locate the repository root from the test output directory.");
    }
}
